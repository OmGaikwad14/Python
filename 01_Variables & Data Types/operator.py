# Arithmetic Operator

a = 5
b = 2

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a ** b) # a^b power
print(a % b) # remainder

# Relational/Comparison Operator

a = 50
b = 20

print(a == b)
print(a != b) # ! - NOT
print(a <= b)
print(a >= b)
print(a < b)
print(a > b)

# Assignment Operator

num = 10

num += 10
num -= 10
num *= 10
num /= 10
num **= 10
num %= 10

print("num :", num)

# Logical Operator

a = 50
b = 30

print(not True)
print(not False)
print(not (a > b))

val1 = True
val2 = False

print("AND Operator :", val1 and val2)
print("OR Operator :", val1 or val2)
